from novel_generator.engine.beat_constants import BEAT_NAMES_CN, resolve_world, derive_seed


class CausalChapterGenerator:
    """因果链章节生成器（旧版，硬编码文本）。

    ⚠️ DEPRECATED — 本生成器每次输出完全相同的硬编码文本，不具随机性。
    推荐使用 IntegratedChapterGenerator（因果结构 + ASP 词库渲染的组合）。
    保留原因：向后兼容旧版 causal 模式。
    完全移除时间：v3.0。
    """

    def __init__(self, wb, plot_state,
                 rubric=None, player_engine=None, quality=None,
                 rashomon=None, info=None, expansion=None,
                 world_sense=None, rhythm=None):
        self._wb = wb
        self._ps = plot_state
        self._dlg = CausalDialogueEngine(wb, plot_state)
        self._char_gen = CharacterGenerator(wb)
        self._scene_gen = SceneGenerator(wb)
        self._battle_gen = BattleGenerator(wb)
        self._rng = wb.get_rng()

        # 质量管线（支持外部注入，避免双重实例化；用 derive_seed 确定性派生子种子，
        # 不消耗主 RNG 熵，确保组件创建顺序不影响全局随机性）
        _ms = wb.seed or 0
        self._quality = quality or TextQualityPipeline(derive_seed(_ms, 'quality'))
        self._rashomon = rashomon or RashomonEngine(derive_seed(_ms, 'rashomon'))
        self._info = info or InfoMatrix()
        self._rubric = rubric or RubricEngine(derive_seed(_ms, 'rubric'))
        self._player_engine = player_engine or PlayerArchetypeEngine(derive_seed(_ms, 'player'))
        self._expansion = expansion or ExpansionEngine(derive_seed(_ms, 'expansion'))
        self._world_sense = world_sense or WorldSenseInjector(derive_seed(_ms, 'world_sense'))
        self._rhythm = rhythm or RhythmEngine(derive_seed(_ms, 'rhythm'))

    # ================================================================
    # 大纲 & 章号调度
    # ================================================================
    def generate_outline(self, chapters_count=80):
        outline = []
        beats = [
            ('opening', 1, 3), ('theme', 4, 6), ('inciting', 7, 12),
            ('debate', 13, 20), ('break_1', 21, 26), ('b_story', 27, 35),
            ('fun_games', 36, 48), ('midpoint', 49, 53), ('bad_guys', 54, 65),
            ('all_lost', 66, 70), ('dark_night', 71, 74), ('break_2', 75, 80),
        ]
        for beat_name, start, end in beats:
            for ch in range(start, end + 1):
                outline.append({
                    'chapter': ch, 'beat': beat_name,
                    'title': BEAT_NAMES_CN.get(beat_name, ''),
                    'sub_index': ch - start + 1,  # 1..N within beat
                    'total_in_beat': end - start + 1,
                })
        return outline

    def generate_chapter(self, chapter_num, outline_entry=None):
        if outline_entry is None:
            beat, sub_idx, total = 'opening', chapter_num, 3
        else:
            beat = outline_entry.get('beat', 'opening')
            sub_idx = outline_entry.get('sub_index', 1)
            total = outline_entry.get('total_in_beat', 3)

        L = []
        events = []
        changes = []

        title = BEAT_NAMES_CN.get(beat, '')
        L.append('第%d章 %s' % (chapter_num, title))
        L.append('')

        # 调度到具体节拍生成器
        gen = getattr(self, '_gen_%s' % beat, None)
        if gen:
            gen(L, chapter_num, sub_idx, total, events, changes)

        # P0: 文本质检管线（节奏 + 去AI味 + 五感）
        L = self._quality.process(L, beat)

        # P1: 复眼叙事——关键节拍自动生成多视角
        if self._rashomon.should_trigger(beat):
            pov_scenes = self._rashomon.generate(beat)
            if pov_scenes:
                L.append('')
                L.append(self._rashomon.format_section(pov_scenes))
                events.append('复眼叙事触发：%d个视角' % len(pov_scenes))

        # P1-C: 三番四震节奏注入——每章注入2次情绪震波
        L = self._rhythm.inject_rhythm(L, beat, frequency=2)

        # Step 2: 事件展开引擎 — 关键事件节点膨胀
        key_expansions = self._get_expansions_for_beat(beat, sub_idx)
        if key_expansions:
            L = self._expansion.inject_expanded_events(L, beat, key_expansions)
        # 弱势节拍额外注入内心独白展开
        L = self._expansion.inject_interiority(L, beat, count=6)  # 5→6

        # Step 3: 世界差异化感官注入
        world_name = resolve_world(beat)
        L = self._world_sense.inject(L, world_name, frequency=6)

        # Step 4: 战斗引擎接入
        if beat in ('bad_guys', 'all_lost') and sub_idx in (3, 7, 10):
            L = self._inject_battle(L, beat, chapter_num)

        # Step 6: 对话密度增强 — 按节拍自动增加对话
        L = self._enhance_dialogue(L, beat, sub_idx, chapter_num)

        # 多线交织：在不同节拍注入其他故事线的碎片视角
        L = self._inject_cross_lines(L, beat, sub_idx, chapter_num)

        # P1: 信息不对称——记录本章叙事策略
        tip = self._info.get_narrative_tip(beat, chapter_num)
        if tip != 'neutral':
            events.append('信息策略：%s' % tip)

        self._ps.add_chapter_summary(chapter_num,
            '第%d章（%s·变体%d）' % (chapter_num, beat, sub_idx),
            events, changes)

        # 千层饼自动触发检查
        truth_result = self._ps.auto_advance_truth()
        if truth_result:
            events.append(
                '千层饼第%d层揭示：%s' % (
                    truth_result['layer'], truth_result['narrative'][:20]
                )
            )

        self._ps.save()
        return '\n'.join(L)

    # ================================================================
    # 对话辅助
    # ================================================================
    def _insert_dialogue(self, L, scene_type, participants, context=None):
        text = self._dlg.generate(scene_type, participants, context)
        if text:
            L.append('')
            L.append(text)
            L.append('')

